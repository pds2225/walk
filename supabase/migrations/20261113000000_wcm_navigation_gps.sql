-- Worldcup Market GPS point capture. Isolated from existing WALK/events/qr_scans.
-- Additive migration: NO DDL on public.events or public.qr_scans; no existing rows changed.
begin;

create table public.wcm_navigation_points (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  measured_at timestamptz not null default now(),
  visitor_id text not null,
  session_id text,
  navigation_id uuid not null,
  store_id text not null check (store_id ~ '^worldcup-market-(0[1-9]|[1-3][0-9]|4[0-5])$'),
  event text not null check (event in ('nav_start','nav_progress','reroute','arrive')),
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  accuracy_m real check (accuracy_m between 0 and 100000),
  geo_consent boolean not null check (geo_consent is true)
);

create index wcm_nav_visitor_time_idx on public.wcm_navigation_points(visitor_id,created_at desc);
create index wcm_nav_route_sequence_idx on public.wcm_navigation_points(navigation_id,measured_at,id);

alter table public.wcm_navigation_points enable row level security;
revoke all on table public.wcm_navigation_points from public, anon, authenticated;
revoke all on sequence public.wcm_navigation_points_id_seq from public, anon, authenticated;
grant select, insert on table public.wcm_navigation_points to service_role;
grant usage, select on sequence public.wcm_navigation_points_id_seq to service_role;

-- A separate retention job applies ONLY to the new GPS table, at 04:30 KST.
-- It never deletes or rewrites a row in the existing events/qr_scans tables.
select cron.schedule(
  'wcm-navigation-gps-retention',
  '30 19 * * *',
  $$delete from public.wcm_navigation_points where created_at < now() - interval '365 days'$$
);
commit;
